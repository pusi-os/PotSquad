#!/usr/bin/env python3
"""PusiMesh v2 golden vectors.

Builds test/pusimesh_v2_vectors.h from an implementation that shares no code
with the firmware: Python's own string handling for presence and the text
alphabets, and (for the frame header) nothing but the layout in
docs/PUSIMESH-V2-SPEC.md. The firmware must reproduce these bytes exactly, or a
receiver and a sender that both believe the spec will still disagree.

The AES ciphertext is deliberately NOT pinned here: the host suite injects a toy
AEAD (it has no crypto library), so the frame vector is the six header bytes and
the thirteen nonce bytes -- the parts no cipher can rescue if they are wrong.

    python3 tools/gen_pusimesh_v2_vectors.py
"""

import os

# ---- the alphabets (spec §5), code point order ------------------------------
LATIN = [ord(' ')] + [ord(c) for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"] \
    + [ord(c) for c in "0123456789"] + [ord(c) for c in ".,?!'-"]

# space, А..Е, Ё, Ж..Я, digits, punctuation
CYR_LETTERS = [0x410 + i for i in range(6)]          # А Б В Г Д Е
CYR_LETTERS += [0x401]                               # Ё
CYR_LETTERS += [0x410 + i for i in range(6, 32)]     # Ж..Я
CYR = [ord(' ')] + CYR_LETTERS \
    + [ord(c) for c in "0123456789"] + [ord(c) for c in ".,?!'-"]

TEXT_END = 63
PART_CHARS = 16
PART_BYTES = 12


def code_of(table, cp):
    for i, t in enumerate(table):
        if t == cp:
            return i
    raise ValueError("code point %x not in table" % cp)


def pack(text, part, table):
    """16 code points (or END) packed 6-bit MSB-first into 12 bytes."""
    codes = []
    start = part * PART_CHARS
    for k in range(PART_CHARS):
        idx = start + k
        codes.append(code_of(table, ord(text[idx])) if idx < len(text) else TEXT_END)
    out = bytearray(PART_BYTES)
    bit = 0
    for code in codes:
        for b in range(5, -1, -1):
            if (code >> b) & 1:
                out[bit >> 3] |= 1 << (7 - (bit & 7))
            bit += 1
    return bytes(out)


# ---- framing helpers --------------------------------------------------------
def presence(node_id, squad_tag, appearance, caps, flags,
             shirt=2, shorts=5, shoes=1, glasses=True, lashes=False, mood=9,
             name=None):
    body = bytearray()
    body += b"PM2"
    body.append(2)
    named = bool(name)
    f = (flags & ~1) | (1 if named else 0)
    body.append(f)
    body += bytes(node_id)
    body += bytes(squad_tag)
    body.append(appearance & 0xFF)
    body.append((appearance >> 8) & 0xFF)
    body.append(caps)
    body.append(shirt & 0x07)
    body.append(shorts & 0x07)
    body.append(shoes & 0x07)
    body.append((1 if glasses else 0) | (2 if lashes else 0) | ((mood & 0x1F) << 2))
    if named:
        raw = name.encode("utf-8")
        assert len(raw) <= 12, "name must fit 12 bytes"
        body += raw + bytes(12 - len(raw))
    return bytes(body)


def frame_header(counter, kind, version=2):
    return b"PU" + bytes([(version << 4) | kind]) + counter.to_bytes(3, "little")


def nonce(node_id, counter):
    return bytes(node_id[:6]) + counter.to_bytes(3, "little") + b"\x00" * 4


def c_array(name, data):
    body = ", ".join("0x%02X" % b for b in data)
    return "static const uint8_t %s[] = { %s };\n" % (name, body)


def c_str(name, s):
    esc = "".join("\\x%02x" % b for b in s.encode("utf-8"))
    return 'static const char %s[] = "%s";\n' % (name, esc)


def main():
    node_id = [0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88]
    squad_tag = [0xA1, 0xB2, 0xC3]
    appearance = 0x3A5C
    caps = 0b0101  # EXT | VOICE

    pres_unnamed = presence(node_id, squad_tag, appearance, caps, flags=0)
    pres_named_lat = presence(node_id, squad_tag, appearance, caps, flags=1, name="POTS")
    pres_named_cyr = presence(node_id, squad_tag, appearance, caps, flags=1, name="ПУСЯ")

    lat_text = "HELLO WORLD 123.?!"
    cyr_text = "ПРИВЕТ МИР! КАК ДЕЛА"
    lat_p0 = pack(lat_text, 0, LATIN)
    lat_p1 = pack(lat_text, 1, LATIN)
    cyr_p0 = pack(cyr_text, 0, CYR)
    cyr_p1 = pack(cyr_text, 1, CYR)

    counter = 0x123456
    kind = 0x8  # TEXT_LONG
    hdr = frame_header(counter, kind)
    nce = nonce(node_id, counter)

    name_ad = b"PXE" + bytes([2, 1]) + bytes(node_id) + "ПУСЯ".encode("utf-8")

    out = []
    out.append("// Generated by tools/gen_pusimesh_v2_vectors.py -- do not edit.\n")
    out.append("// Independent implementation of docs/PUSIMESH-V2-SPEC.md; the\n")
    out.append("// firmware must reproduce these byte for byte. See test/pusimesh_v2_test.cpp.\n")
    out.append("#pragma once\n#include <stdint.h>\n\nnamespace PusiMesh2Vectors {\n\n")
    out.append(c_array("NODE_ID", node_id))
    out.append(c_array("SQUAD_TAG", squad_tag))
    out.append("static const uint16_t APPEARANCE = 0x%04X;\n" % appearance)
    out.append("static const uint8_t CAPS = 0x%02X;\n\n" % caps)
    out.append(c_array("PRES_UNNAMED", pres_unnamed))
    out.append(c_array("PRES_NAMED_LATIN", pres_named_lat))
    out.append(c_array("PRES_NAMED_CYR", pres_named_cyr))
    out.append(c_array("NAME_AD_CYR", name_ad))
    out.append("\n")
    out.append(c_str("TEXT_LATIN", lat_text))
    out.append(c_str("TEXT_CYR", cyr_text))
    out.append(c_array("TEXT_LATIN_P0", lat_p0))
    out.append(c_array("TEXT_LATIN_P1", lat_p1))
    out.append(c_array("TEXT_CYR_P0", cyr_p0))
    out.append(c_array("TEXT_CYR_P1", cyr_p1))
    out.append("\n")
    out.append("static const uint32_t FRAME_COUNTER = 0x%06X;\n" % counter)
    out.append("static const uint8_t FRAME_KIND = 0x%02X;\n" % kind)
    out.append(c_array("FRAME_HDR", hdr))
    out.append(c_array("FRAME_NONCE", nce))
    out.append("\n} // namespace PusiMesh2Vectors\n")

    dst = os.path.join(os.path.dirname(__file__), "..", "test", "pusimesh_v2_vectors.h")
    with open(dst, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
